def main() -> int:
    if len(sys.argv) != 1:
        print("usage: scripts/check-prorata-weth-vault-artifact.py", file=sys.stderr)
        return 2
    errors: list[str] = []
    source = read(SOURCE, errors)
    code = read(CODE, errors)
    artifact = read(ARTIFACT, errors)
    generator = read(GENERATOR, errors)
    if not errors:
        check_runtime(code, errors)
        check_abi(source, artifact, errors)
        check_pins(source, artifact, generator, errors)
    if errors:
        for error in errors:
            print(f"REGRESSION — PRORATA WETH vault artifact: {error}", file=sys.stderr)
        return 1
    print(
        "OK — PRORATA WETH vault artifact: 25 selectors; 10 auxiliaries; "
        f"{RUNTIME_BYTES} runtime bytes; sha256 {RUNTIME_SHA256}; "
        "kernel compile witness green"
    )
    return 0


