def compact(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def read(path: Path, errors: list[str]) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        errors.append(f"cannot read {path.relative_to(ROOT)}: {exc}")
        return ""


def require(text: str, snippet: str, owner: str, errors: list[str]) -> None:
    if compact(snippet) not in compact(text):
        errors.append(f"{owner}: missing exact pin: {compact(snippet)}")


def check_runtime(text: str, errors: list[str]) -> None:
    literal_rows: dict[int, bytes] = {}
    chunk_re = re.compile(
        r"private def prorataWethVaultCodeChunk(\d+)\s*:\s*Bytes\s*:=\s*\[(.*?)\]",
        re.S,
    )
    for raw_index, body in chunk_re.findall(text):
        index = int(raw_index)
        if index in literal_rows:
            errors.append(f"runtime chunk {index}: duplicate literal definition")
            continue
        residue = re.sub(r"0x[0-9a-fA-F]{2}|[\s,]", "", body)
        if residue:
            errors.append(f"runtime chunk {raw_index}: unparsed content {residue!r}")
            continue
        tokens = re.findall(r"0x[0-9a-fA-F]{2}", body)
        literal_rows[index] = bytes(int(token, 16) for token in tokens)

    alias_rows: dict[int, int] = {}
    alias_re = re.compile(
        r"private def prorataWethVaultCodeChunk(\d+)\s*:\s*Bytes\s*:=\s*"
        r"prorataWethVaultCodeChunk(\d+)\b"
    )
    for raw_index, raw_target in alias_re.findall(text):
        index = int(raw_index)
        if index in alias_rows:
            errors.append(f"runtime chunk {index}: duplicate alias definition")
            continue
        alias_rows[index] = int(raw_target)

    if not literal_rows:
        errors.append("runtime: no generated byte chunks found")
        return
    overlapping = sorted(set(literal_rows) & set(alias_rows))
    if overlapping:
        errors.append(f"runtime: chunks defined as both literal and alias: {overlapping}")
    indices = sorted(set(literal_rows) | set(alias_rows))
    if indices != list(range(69)):
        errors.append(f"runtime: non-contiguous chunk indices {indices}")
    parsed_defs = len(literal_rows) + len(alias_rows)
    declared_defs = text.count("private def prorataWethVaultCodeChunk")
    if parsed_defs != declared_defs:
        errors.append(
            f"runtime: parsed {parsed_defs} chunk definitions but found {declared_defs} declarations"
        )
    if len(literal_rows) != 68 or alias_rows != {48: 34}:
        errors.append(
            "runtime: expected 68 literal chunks and canonical alias chunk48 -> chunk34; "
            f"found {len(literal_rows)} literals and aliases {alias_rows}"
        )

    resolved: dict[int, bytes] = {}

    def resolve(index: int, active: set[int]) -> bytes:
        if index in resolved:
            return resolved[index]
        if index in active:
            errors.append(f"runtime chunk {index}: alias cycle")
            return b""
        if index in literal_rows:
            resolved[index] = literal_rows[index]
            return resolved[index]
        target = alias_rows.get(index)
        if target is None:
            errors.append(f"runtime chunk {index}: missing definition")
            return b""
        if target >= index:
            errors.append(f"runtime chunk {index}: alias target {target} is not earlier")
        resolved[index] = resolve(target, active | {index})
        return resolved[index]

    rows = [(index, resolve(index, set())) for index in range(69)]
    for index, chunk in rows[:-1]:
        if len(chunk) != 256:
            errors.append(f"runtime chunk {index}: expected 256 bytes, found {len(chunk)}")
    if len(rows[-1][1]) != 73:
        errors.append(f"runtime final chunk: expected 73 bytes, found {len(rows[-1][1])}")

    runtime = b"".join(chunk for _, chunk in rows)
    if len(runtime) != RUNTIME_BYTES:
        errors.append(f"runtime: expected {RUNTIME_BYTES} bytes, found {len(runtime)}")
    digest = hashlib.sha256(runtime).hexdigest()
    if digest != RUNTIME_SHA256:
        errors.append(f"runtime: SHA-256 {digest}, expected {RUNTIME_SHA256}")
    if len(runtime) > 24_576:
        errors.append(f"runtime: {len(runtime)} bytes exceeds EIP-170")

    join_match = re.search(
        r"def prorataWethVaultCode\s*:\s*Bytes\s*:=\s*(.*?)\n\n/-- Kernel-checked",
        text,
        re.S,
    )
    if join_match is None:
        errors.append("runtime: committed literal join is missing")
    else:
        joined = [int(value) for value in re.findall(
            r"prorataWethVaultCodeChunk(\d+)", join_match.group(1)
        )]
        if joined != list(range(69)):
            errors.append(f"runtime: literal joins chunks in the wrong order: {joined}")

    require(text, f"The {RUNTIME_BYTES}-byte compiled EVM runtime.", "runtime", errors)
    require(
        text,
        "Prog.compile ProrataWethVault.vault = some prorataWethVaultCode := by decide +kernel",
        "runtime",
        errors,
    )


def check_abi(source: str, artifact: str, errors: list[str]) -> None:
    block_match = re.search(
        r"def vaultFuncs\s*:\s*List \(B256 × Func\)\s*:=\s*(.*?)\n\ntheorem vaultFuncs_sorted",
        source,
        re.S,
    )
    if block_match is None:
        errors.append("source: vaultFuncs block is missing")
        return
    block = block_match.group(1)
    entry_re = re.compile(
        r"\(selector\s+\"([^\"]+)\"\s+\[(.*?)\],\s*routed\s+(\d+)\s+([A-Za-z0-9_]+)\)",
        re.S,
    )
    observed = []
    for name, args, words, body in entry_re.findall(block):
        observed.append((name, re.sub(r"\s+", "", args), int(words), body))
    expected = [(name, args, words, body) for name, args, words, body, _ in ABI]
    if observed != expected:
        errors.append(f"source: ABI routes differ\n  observed={observed}\n  expected={expected}")
    if block.count("selector \"") != len(ABI):
        errors.append("source: ABI block contains an unparsed or extra selector entry")

    selector_match = re.search(
        r"theorem vaultSelectors_exact\s*:(.*?)\:= by",
        artifact,
        re.S,
    )
    if selector_match is None:
        errors.append("artifact: vaultSelectors_exact is missing")
    else:
        observed_selectors = re.findall(r"0x([0-9a-fA-F]{8})", selector_match.group(1))
        expected_selectors = [selector for *_, selector in ABI]
        if observed_selectors != expected_selectors:
            errors.append(
                f"artifact: selector list differs: {observed_selectors} != {expected_selectors}"
            )


