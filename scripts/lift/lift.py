def _patch(t: Any) -> Any:
    kind = t[0]
    if kind == 'join_ref':
        return t
    if kind == 'branchTo' and isinstance(t[2], tuple):
        return ('branchTo', _patch(t[1]), wrapper_index[t[2][1]], t[3])
    if kind in ('next',):
        return (kind, t[1], _patch(t[2]), t[3])
    if kind == 'dest':
        return ('dest', _patch(t[1]), t[2])
    if kind == 'branch':
        return ('branch', _patch(t[1]), _patch(t[2]), t[3])
    if kind == 'branchTo':
        return ('branchTo', _patch(t[1]), t[2], t[3])
    if kind == 'callNext':
        return ('callNext', t[1], _patch(t[2]), t[3])
    return t

