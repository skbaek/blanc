# Pointwise generalization for join entries
def pointwise_generalization(frames: List[List[Tuple[Any, ...]]]) -> Tuple[Optional[Tuple[Tuple[Any, ...], ...]], Optional[str]]:
    if not frames:
        return None, "No incoming frames"
    lengths = [len(f) for f in frames]
    if len(set(lengths)) > 1:
        return None, f"Frame lengths disagree: {lengths}"
    flen = lengths[0]
    gen = []
    for i in range(flen):
        vals = [f[i] for f in frames]
        ret_count = sum(1 for v in vals if v[0] == 'ret')
        if ret_count > 0:
            if ret_count != len(vals):
                return None, f"Return positions disagree at index {i}"
            gen.append(('ret',))
        elif all(v == vals[0] for v in vals):
            if vals[0][0] == 'const' and vals[0][1] not in jumpdests and not CONST_MEM:
                gen.append(('unk',))
            else:
                gen.append(vals[0])
        else:
            if JOIN_EXEMPT and any(v[0] == 'const' and v[1] in jumpdests for v in vals):
                return None, f"PROBE exempt: jump destinations disagree at index {i}"
            gen.append(('unk',))
    return tuple(gen), None

