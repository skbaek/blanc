WRAPPERS: Set[int] = set()
SELECTOR_MAP: Dict[int, int] = {} # selector_int -> wrapper_pc
_pcs = sorted(inst_map)
for _i in range(len(_pcs) - 4):
    _a, _b, _c, _d, _e = (_pcs[_i + j] for j in range(5))
    if (inst_map[_a][0] == 0x80 and inst_map[_b][0] == 0x63 and inst_map[_c][0] == 0x14
            and (0x60 <= inst_map[_d][0] <= 0x62) and inst_map[_e][0] == 0x57):
        sel = int.from_bytes(inst_map[_b][2], "big")
        tgt_pc = int.from_bytes(inst_map[_d][2], "big")
        WRAPPERS.add(tgt_pc)
        SELECTOR_MAP[sel] = tgt_pc

deferred_wrappers: List[Tuple[int, Tuple[Tuple[Any, ...], ...], int, Any]] = []

def generalize_frame(frame: List[Tuple[Any, ...]]) -> Tuple[Tuple[Any, ...], ...]:
    gen = []
    for v in frame:
        if v[0] == 'const' and v[1] in jumpdests:
            gen.append(v)
        elif v[0] == 'ret':
            gen.append(v)
        else:
            gen.append(('unk',))
    return tuple(gen)

# Pointwise generalization for join entries
def pointwise_generalization(frames: List[List[Tuple[Any, ...]]]) -> Tuple[Optional[Tuple[Tuple[Any, ...], ...]], Optional[str]]:
    if not frames:
        return None, "No incoming frames"
    lengths = [len(f) for f in frames]
    if len(set(lengths)) > 1:
        return None, f"Frame lengths disagree: {lengths}"
    flen = lengths[0]
    gen = []
    for i in range(flen):
        vals = [f[i] for f in frames]
        ret_count = sum(1 for v in vals if v[0] == 'ret')
        if ret_count > 0:
            if ret_count != len(vals):
                return None, f"Return positions disagree at index {i}"
            gen.append(('ret',))
        elif all(v == vals[0] for v in vals):
            if vals[0][0] == 'const' and vals[0][1] not in jumpdests:
                gen.append(('unk',))
            else:
                gen.append(vals[0])
        else:
            gen.append(('unk',))
    return tuple(gen), None

