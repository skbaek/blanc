def _def_arms(source: str, header: str, path: Path) -> List[Tuple[str, str]]:
    """The one-line `| .ctor[ arg], words => rhs` arms of the Lean def starting at `header`."""
    start = source.find(header)
    if start < 0 or source.count(header) != 1:
        raise SystemExit(f"lift: cannot locate `{header}` exactly once in {path}")
    body = source[start + len(header):].split("\n\n", 1)[0]
    arms = []
    for line in body.splitlines():
        m = re.match(r"^\s*\| (\.[\w .]+?), words =>\s*(.*)$", line)
        if m:
            arms.append((m.group(1).strip(), m.group(2).strip()))
    return arms


def _arm_shape(rhs: str, source: str) -> Optional[Tuple[int, int]]:
    """Stack shape (pops, pushes) of a transfer right-hand side, None if unrecognized."""
    fixed = {
        "binaryTransfer words": (2, 1),
        "unaryTransfer words": (1, 1),
        "some (none :: words)": (0, 1),
        "dropTwoTransfer words": (2, 0),
        "dropOneTransfer words": (1, 0),
    }
    if rhs in fixed:
        return fixed[rhs]
    m = re.fullmatch(r"dropTransfer (\d+) words", rhs)
    if m:
        return (int(m.group(1)), 0)
    m = re.fullmatch(r"(callTransfer|staticcallTransfer) words", rhs)
    if m:
        dm = re.search(rf"def {m.group(1)} : Pattern → Option Pattern\n\s*\| ((?:_ :: )+)words => some \(none :: words\)", source)
        if dm:
            return (dm.group(1).count("_ ::"), 1)
    return None


def check_lean_transfers(root: Path) -> None:
    """Fail unless every `LEAN_REG` row has a lifted Lean transfer of the producer's stack shape."""
    transfer_path = root / "Blanc/Lift/Transfer.lean"
    regular_path = root / "Blanc/AbstractStackTransfer.lean"
    transfer = transfer_path.read_text()
    regular = regular_path.read_text()
    ninst = dict(_def_arms(transfer, "def ninstTransfer : Ninst → Pattern → Option Pattern", transfer_path))
    lift = dict(_def_arms(transfer, "def liftRegularTransfer : Rinst → Pattern → Option Pattern", transfer_path))
    reg = dict(_def_arms(regular, "def regularTransfer : Rinst → Pattern → Option Pattern", regular_path))
    if ninst.get(".reg r") != "liftRegularTransfer r words":
        raise SystemExit("lift: ninstTransfer no longer routes `.reg r` through liftRegularTransfer")
    errors = []
    for op, lean in sorted(LEAN_REG.items()):
        name, pops, pushes = OPCODE_EFFECTS[op]
        if lean.startswith(".exec "):
            rhs = ninst.get(lean)
        else:
            ctor = lean[len(".reg "):]
            m = re.fullmatch(r"\(\.log (\d)\)", ctor)
            if m:
                arm = lift.get(".log n")
                rhs = None if arm != "dropTransfer (n.val + 2) words" else f"dropTransfer {int(m.group(1)) + 2} words"
            else:
                rhs = lift.get(ctor, reg.get(ctor))
        shape = _arm_shape(rhs, transfer + "\n" + regular) if rhs is not None else None
        if shape is None:
            errors.append(f"{name} (0x{op:02x}) `{lean}`: no lifted transfer arm")
        elif shape != (pops, pushes):
            errors.append(f"{name} (0x{op:02x}) `{lean}`: Lean shape {shape} != producer ({pops}, {pushes})")
    if errors:
        raise SystemExit("lift: producer opcode table disagrees with the Lean transfer set:\n  " + "\n  ".join(errors))


def run_registry(args: argparse.Namespace) -> int:
    """Regenerate every registered certificate and compare with (or write) the committed files."""
    root = args.blanc_root
    registry_path = args.registry
    registry = json.loads(registry_path.read_text())
    rows = registry["certificates"]
    if args.only:
        rows = [r for r in rows if r["id"] in args.only]
        if len(rows) != len(set(args.only)):
            print(f"lift: unknown --only id among {args.only}", file=sys.stderr)
            return 2
    failures = 0
    with tempfile.TemporaryDirectory(prefix="lift-registry-") as tmp:
        for row in rows:
            ident = row["id"]
            hex_file = root / row["input"]["hex"]
            file_sha = hashlib.sha256(hex_file.read_bytes()).hexdigest()
            if file_sha != row["input"]["file_sha256"]:
                print(f"FAIL {ident}: input {row['input']['hex']} file sha256 {file_sha} != registered {row['input']['file_sha256']}")
                failures += 1
                continue
            out = Path(tmp) / ident
            out.mkdir()
            argv = [sys.executable, str(SCRIPT), "--blanc-root", str(root),
                    "--hex", str(hex_file), "--sha256", row["input"]["runtime_sha256"],
                    "--namespace", row["namespace"], "--cert-out", str(out / "Cert.lean")]
            opts = row.get("options", {})
            if opts.get("join_entries") is False:
                argv.append("--no-join-entries")
            if "wrapper_order" in opts:
                argv += ["--wrapper-order", opts["wrapper_order"]]
            if opts.get("fold") is True:
                argv.append("--fold")
            if "header" in row:
                argv += ["--header", row["header"]]
            check = row.get("check")
            if check:
                argv += ["--check-out", str(out / "Check.lean"), "--check-header", check["header"],
                         "--check-split-nodes", str(check.get("split_nodes", 0))]
            proc = subprocess.run(argv, capture_output=True, text=True, timeout=args.timeout)
            if proc.returncode != 0:
                print(f"FAIL {ident}: producer exit {proc.returncode}\n{proc.stdout}{proc.stderr}")
                failures += 1
                continue
            summary = next((l for l in proc.stdout.splitlines() if l.startswith("Counts:")), "")
            pairs = [(out / "Cert.lean", root / row["cert"])]
            if check:
                pairs.append((out / "Check.lean", root / check["path"]))
            for produced, committed in pairs:
                rel = committed.relative_to(root)
                if args.write:
                    committed.parent.mkdir(parents=True, exist_ok=True)
                    committed.write_bytes(produced.read_bytes())
                    print(f"WROTE {ident}: {rel}")
                elif not committed.exists():
                    print(f"FAIL {ident}: {rel} is missing")
                    failures += 1
                elif produced.read_bytes() != committed.read_bytes():
                    a, b = produced.read_bytes(), committed.read_bytes()
                    first = next((i for i in range(min(len(a), len(b))) if a[i] != b[i]), min(len(a), len(b)))
                    line = a[:first].count(b"\n") + 1
                    print(f"FAIL {ident}: {rel} differs from its regeneration (first difference at byte {first}, line {line}; sizes {len(b)} committed vs {len(a)} regenerated)")
                    failures += 1
                else:
                    print(f"ok   {ident}: {rel} byte-identical ({committed.stat().st_size} bytes) {summary}")
    total = len(rows)
    if failures:
        print(f"check-lift-certificates: FAIL ({failures} failure(s) over {total} registered certificate(s))")
        return 1
    verb = "written" if args.write else "regenerated byte-identically"
    print(f"check-lift-certificates: PASS ({total} registered certificate(s) {verb})")
    return 0


