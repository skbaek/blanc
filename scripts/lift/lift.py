def tree_to_json(t: Any) -> Dict[str, Any]:
    kind = t[0]
    if kind == 'join_ref':
        return {"kind": "join", "pc": t[2], "target_entry": t[1]}
    elif kind == 'next':
        op, d = t[1]
        return {"kind": "next", "pc": t[3], "op": hex(op), "data": d.hex(), "sub": tree_to_json(t[2])}
    elif kind == 'last':
        return {"kind": "last", "pc": t[2], "op": hex(t[1])}
    elif kind == 'dest':
        return {"kind": "dest", "pc": t[2], "sub": tree_to_json(t[1])}
    elif kind == 'branch':
        return {"kind": "branch", "pc": t[3], "fall": tree_to_json(t[1]), "taken": tree_to_json(t[2])}
    elif kind == 'branchTo':
        return {"kind": "branchTo", "pc": t[3], "fall": tree_to_json(t[1]), "target_entry": t[2]}
    elif kind == 'jump':
        return {"kind": "jump", "pc": t[2], "target_entry": t[1]}
    elif kind == 'callNext':
        return {"kind": "callNext", "pc": t[3], "target_entry": t[1], "continuation": tree_to_json(t[2])}
    elif kind == 'ret':
        return {"kind": "ret", "pc": t[1]}
    elif kind == 'undefined':
        return {"kind": "undefined", "pc": t[1]}
    else:
        return {"kind": "unknown"}

def count_tree_nodes(t: Any) -> int:
    kind = t[0]
    if kind == 'join_ref':
        return 1
    elif kind == 'next':
        return 1 + count_tree_nodes(t[2])
    elif kind == 'dest':
        return 1 + count_tree_nodes(t[1])
    elif kind == 'branch':
        return 1 + count_tree_nodes(t[1]) + count_tree_nodes(t[2])
    elif kind == 'branchTo':
        return 1 + count_tree_nodes(t[1])
    elif kind == 'jump':
        return 1
    elif kind == 'callNext':
        return 1 + count_tree_nodes(t[2])
    elif kind in ('last', 'ret', 'undefined'):
        return 1
    return 1

