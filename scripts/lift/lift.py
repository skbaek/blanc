def byte_lines(data: bytes) -> List[str]:
    """Code bytes, 16 per line."""
    out = []
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        hex_chunk = ", ".join(f"0x{b:02x}" for b in chunk)
        comma = "," if i + 16 < len(data) else ""
        out.append(f"  {hex_chunk}{comma}")
    return out


