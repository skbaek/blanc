    cur_pc = pc
    op = code[pc]
    if 0x5f <= op <= 0x7f:
        size = op - 0x5f
        data = code[pc + 1 : pc + 1 + size]
        pc += 1 + size
        inst_map[cur_pc] = (op, 1 + size, data)
    else:
        pc += 1
        inst_map[cur_pc] = (op, 1, b"")

