#!/usr/bin/env python3
"""Canonical lift-certificate producer for deployed EVM bytecode (untrusted).

This is Blanc's one registered generator of `Blanc/Lift/**/Cert.lean` (and, where
registered, the matching per-entry `Check.lean`).  It recovers a certificate of
frame-relative control structure from raw runtime bytes; it proves nothing.  The
only trust boundary is Lean: `Cert.check code cert = true`, decided by the kernel
in the generated or hand-written `Check.lean`, is what a lift theorem consumes.

Provenance.  This file is the union of the historical producer forks kept as
Plans evidence (`solc-bytecode-v1/w3/lift.py`, `beacon-deposit-bytecode-v1/w0/lift.py`,
`vyper-3crv-bytecode-v1/v1/lift.py`) and the deployed Lido adaptation
(`deployed-lido-vyper-v1/certificate/generate.py`: PUSH0, TLOAD/TSTORE, SLT,
EXTCODESIZE, compatible-join repair, join-aware call continuations).  The two
exploration differences of the solc-w3 fork are options (`--no-join-entries`,
`--wrapper-order fall-first`), not code paths per contract.  `--fold` (registry
option `"fold": true`) folds ADD, MUL, SUB, LT, GT, EQ and ISZERO over constant
operands exactly as `foldConst` in `Blanc/Lift/Check.lean`; off by default, so
every certificate registered without it regenerates byte-identically.

Supported opcodes.  `LEAN_REG` maps each regular opcode the producer may emit to
its Lean `Ninst`; every row is checked, on each run, against the arms of
`ninstTransfer`/`liftRegularTransfer` (`Blanc/Lift/Transfer.lean`) and
`regularTransfer` (`Blanc/AbstractStackTransfer.lean`), including the arm's stack
shape.  An opcode without a lifted transfer is reported and the run fails; there
is no way to assume one.

Modes.
  lift:      --hex FILE --sha256 DIGEST --namespace NS --cert-out FILE [--check-out FILE] ...
  registry:  --registry scripts/lift/certificates.json (--verify | --write) [--only ID]
The registry mode regenerates every registered certificate from its committed
input and byte-compares (`--verify`, used by `scripts/check-lift-certificates.sh`)
or rewrites (`--write`) the committed Lean files.
"""

