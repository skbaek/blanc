# 3. Abstract state transfer (mirror of absNinst)
W256 = 1 << 256
# foldConst's binary ops; x = top of stack, y = second (Jaune's applyBinary order)
FOLD2 = {
    0x01: lambda x, y: x + y,               # ADD
    0x02: lambda x, y: x * y,               # MUL
    0x03: lambda x, y: x - y,               # SUB
    0x10: lambda x, y: 1 if x < y else 0,   # LT
    0x11: lambda x, y: 1 if x > y else 0,   # GT
    0x14: lambda x, y: 1 if x == y else 0,  # EQ
}
def step_inst(op: int, data: bytes, stack: List[Tuple[Any, ...]], cur_pc: Optional[int] = None) -> Optional[List[Tuple[Any, ...]]]:
    # Check if opcode is supported in the checker model
    if op not in BASE_SUPPORTED_OPS:
        if cur_pc is not None:
            encountered_unsupported.setdefault(op, []).append(cur_pc)
        return None

    st = list(stack)
    if 0x5f <= op <= 0x7f:
        val = int.from_bytes(data, 'big')
        st.insert(0, ('const', val))
        return st
    elif 0x80 <= op <= 0x8f: # DUPn
        idx = op - 0x80
        if idx >= len(st): return None
        st.insert(0, st[idx])
        return st
    elif 0x90 <= op <= 0x9f: # SWAPn
        idx = op - 0x8f
        if idx >= len(st): return None
        st[0], st[idx] = st[idx], st[0]
        return st
    elif op == 0x50: # POP
        if not st: return None
        st.pop(0)
        return st
    elif op in (0x01, 0x02, 0x03, 0x04, 0x0a, 0x10, 0x11, 0x14, 0x16, 0x1c, 0x20): # 2 -> 1
        if len(st) < 2: return None
        x, y = st.pop(0), st.pop(0)
        if args.fold and op in FOLD2 and x[0] == 'const' and y[0] == 'const':
            st.insert(0, ('const', FOLD2[op](x[1], y[1]) % W256))
        else:
            st.insert(0, ('unk',))
        return st
    elif op in (0x15, 0x19, 0x31, 0x35, 0x51, 0x54): # 1 -> 1
        if len(st) < 1: return None
        x = st.pop(0)
        if args.fold and op == 0x15 and x[0] == 'const':
            st.insert(0, ('const', 1 if x[1] == 0 else 0))
        else:
            st.insert(0, ('unk',))
        return st
    elif op in (0x30, 0x32, 0x33, 0x34, 0x36, 0x42, 0x5a): # 0 -> 1
        st.insert(0, ('unk',))
        return st
    elif op in (0x52, 0x55): # 2 -> 0
        if len(st) < 2: return None
        st.pop(0); st.pop(0)
        return st
    elif op in (0xa0, 0xa1, 0xa2, 0xa3, 0xa4): # LOGn: n + 2 -> 0
        n = op - 0xa0
        if len(st) < n + 2: return None
        for _ in range(n + 2): st.pop(0)
        return st
    elif op == 0xf1: # CALL: 7 -> 1
        if len(st) < 7: return None
        for _ in range(7): st.pop(0)
        st.insert(0, ('unk',))
        return st
    elif op in BASE_SUPPORTED_OPS:  # natural effect for every other supported op
        name, pops, pushes = OPCODE_EFFECTS[op]
        if len(st) < pops: return None
        for _ in range(pops): st.pop(0)
        for _ in range(pushes): st.insert(0, ('unk',))
        return st
    else:
        return None

def goto_compat(caller_frame: List[Tuple[Any, ...]], entry_frame: Tuple[Tuple[Any, ...], ...]) -> bool:
    if len(caller_frame) != len(entry_frame):
        return False
    for a, e in zip(caller_frame, entry_frame):
        if e[0] == 'unk':
            continue
        elif e[0] == 'const':
            if a[0] != 'const' or a[1] != e[1]:
                return False
        elif e[0] == 'ret':
            if a[0] != 'ret':
                return False
        else:
            return False
    return True

def call_compat(t: int, caller_frame: List[Tuple[Any, ...]], callee_frame: Tuple[Tuple[Any, ...], ...]) -> bool:
    if len(caller_frame) < len(callee_frame):
        return False
    for a, e in zip(caller_frame, callee_frame):
        if e[0] == 'unk':
            continue
        elif e[0] == 'const':
            if a[0] != 'const' or a[1] != e[1]:
                return False
        elif e[0] == 'ret':
            if a[0] != 'const' or a[1] != t:
                return False
        else:
            return False
    return True

# 4. Callee analysis (solc convention)
callee_memo: Dict[Tuple[int, Tuple[Tuple[Any, ...], ...]], Tuple[bool, Optional[int]]] = {}

explore_budget = [400000]

def check_callee(t: int, callee_frame: Tuple[Tuple[Any, ...], ...]) -> Tuple[bool, Optional[int]]:
    key = (t, callee_frame)
    if key in callee_memo:
        return callee_memo[key]
    
    returns = set()
    failed = False
    
    def explore(cur_pc: int, cur_st: List[Tuple[Any, ...]], path: Set[Tuple[int, Tuple[Tuple[Any, ...], ...]]]):
        nonlocal failed
        if failed: return
        state_key = (cur_pc, tuple(cur_st))
        if state_key in seen:
            return
        seen.add(state_key)
        explore_budget[0] -= 1
        if explore_budget[0] < 0:
            raise RuntimeError("callee exploration budget exhausted")
        new_path = path | {state_key}
        
        while True:
            if cur_pc not in inst_map:
                failed = True
                return
            op, sz, d = inst_map[cur_pc]
            if op == 0x5b: # JUMPDEST
                cur_pc += 1
            elif op == 0x57: # JUMPI
                if len(cur_st) < 2:
                    failed = True
                    return
                tgt = cur_st[0]
                rem = cur_st[2:]
                explore(cur_pc + 1, rem, new_path)
                if tgt[0] == 'const':
                    if not any(p == tgt[1] for (p, _) in new_path):
                        explore(tgt[1], rem, new_path)
                else:
                    failed = True
                return
            elif op == 0x56: # JUMP
                if len(cur_st) < 1:
                    failed = True
                    return
                tgt = cur_st[0]
                rem = cur_st[1:]
                if tgt[0] == 'ret':
                    returns.add(len(rem))
                    return
                elif tgt[0] == 'const':
                    if any(p == tgt[1] for (p, _) in new_path):
                        return # Loop back-edge encountered in callee, cycle terminates
                    sub_call = None
                    for i, v in enumerate(rem):
                        if v[0] == 'const' and v[1] in jumpdests:
                            sub_cf = (('unk',),) * i + (('ret',),)
                            is_c, sub_rets = check_callee(tgt[1], sub_cf)
                            if is_c:
                                sub_call = (i, sub_rets)
                            break
                    if sub_call is not None:
                        i, sub_rets = sub_call
                        ret_pc = rem[i][1]
                        cont_st = [('unk',)] * sub_rets + list(rem[i+1:])
                        explore(ret_pc, cont_st, new_path)
                        return
                    else:
                        explore(tgt[1], rem, new_path)
                        return
                else:
                    failed = True
                    return
            elif op in (0x00, 0xf3, 0xfd, 0xfe, 0xff):
                return
            else:
                nxt = step_inst(op, d, cur_st, cur_pc)
                if nxt is None:
                    failed = True
                    return
                cur_st = nxt
                cur_pc += sz

    seen: Set[Tuple[int, Tuple[Tuple[Any, ...], ...]]] = set()
    try:
        explore(t, list(callee_frame), set())
    except (RecursionError, RuntimeError):
        failed = True
    if not failed and len(returns) == 1:
        res = (True, list(returns)[0])
    else:
        res = (False, None)
    callee_memo[key] = res
    return res

