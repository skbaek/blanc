    print("=== Unsupported opcodes: no lifted Lean transfer (Blanc/Lift/Transfer.lean) ===", file=sys.stderr)
    for op in sorted(unsupported_in_scan.keys()):
        name, pops, pushes = OPCODE_EFFECTS.get(op, ("UNKNOWN", 0, 0))
        occurrences = len(unsupported_in_scan[op])
        pcs_str = ", ".join(f"0x{pc:04x}" for pc in unsupported_in_scan[op][:5])
        if occurrences > 5:
            pcs_str += f", ... ({occurrences} total)"
        print(f"  - {name} (0x{op:02x}): pops {pops}, pushes {pushes} [occurrences: {occurrences} at {pcs_str}]", file=sys.stderr)
    sys.exit(1)

